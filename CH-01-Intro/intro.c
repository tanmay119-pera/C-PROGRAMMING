// FIRST CODE IN C PROGRAMMING (SYNTAX OF C)

#include <stdio.h>

int main() {
    printf("Hello, World!");
    return 0;
}

/*

#include <stdio.h>: This tells the compiler to load the "Standard Input/Output" library, 
which contains the code needed to print text to the screen and read keyboard input.

int main(): This is the starting line for your program. The computer always looks for main to know where to begin 
executing code.

printf(...): This is a built-in function that prints text to the screen.

return 0;: This signals to the computer's operating system that the program finished successfully without any errors.

*/